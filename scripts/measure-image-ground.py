"""
Measure the ground each supplied photograph sits on, and write src/data/grounds.ts.

Why this exists: the 23 photographs were commissioned on a single warm off-white
(#FAFAF9), but the set came back on warm beige grounds that drift from #D4CBC2 to
#F4F0EB at the top edge, each with its own vertical gradient. Dropping them onto
one flat frame colour would show a visible step at every image edge.

So each frame paints the gradient measured from that image's own two edges. The
image is then contained rather than cropped, and the letterbox bands continue the
photograph's own tone instead of framing it.

Run from the project root:  python scripts/measure-image-ground.py
"""

import glob
import io
import os

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'data', 'grounds.ts')

# The outer 2px are skipped: generators commonly leave a resampling fringe there
# that is not representative of the ground.
EDGE_SKIP = 2
EDGE_DEPTH = 12


def hexf(c) -> str:
    return '#%02X%02X%02X' % tuple(int(round(min(255, max(0, v)))) for v in c)


def measure(path: str) -> dict:
    a = np.asarray(Image.open(path).convert('RGB')).astype(np.float32)
    h, w, _ = a.shape
    lo, hi = EDGE_SKIP, EDGE_SKIP + EDGE_DEPTH
    return {
        'slug': os.path.basename(path)[: -len('.png')],
        'w': w,
        'h': h,
        'top': hexf(a[lo:hi, :, :].reshape(-1, 3).mean(axis=0)),
        'bottom': hexf(a[-hi:-lo, :, :].reshape(-1, 3).mean(axis=0)),
    }


rows = sorted(
    (measure(p) for p in glob.glob(os.path.join(ROOT, 'src', 'assets', '**', '*.png'), recursive=True)),
    key=lambda r: r['slug'],
)

HEADER = """/**
 * Measured frame grounds, generated by scripts/measure-image-ground.py.
 *
 * Every supplied photograph sits on its own warm gradient, and those grounds
 * drift across the set (#D4CBC2 to #F4F0EB at the top edge). Frames therefore
 * letterbox with object-fit: contain rather than crop — six of the twelve
 * product shots cannot survive any uniform crop without cutting metal — and
 * each frame paints the gradient measured from that image's own edges, so the
 * bands read as a continuation of the photograph rather than as a border.
 *
 * Do not hand-edit: re-run the script instead.
 */
export interface Ground {
  /** Intrinsic width in pixels. */
  w: number;
  /** Intrinsic height in pixels. */
  h: number;
  /** Mean colour of the top edge strip. */
  top: string;
  /** Mean colour of the bottom edge strip. */
  bottom: string;
}

export const grounds: Record<string, Ground> = {
"""

FOOTER = """};

/** Frame ground as a CSS gradient; falls back to the neutral stone ground. */
export function groundFor(slug: string): string {
  const g = grounds[slug];
  if (!g) return 'var(--color-muted)';
  return `linear-gradient(to bottom, ${g.top}, ${g.bottom})`;
}

/**
 * The photograph's own aspect ratio, as a CSS value.
 *
 * Used wherever one image stands alone — a product page, a post banner — so that
 * frame bands disappear entirely. Grids still pass a fixed ratio instead, because
 * cards of four different shapes in one row look like a mistake.
 */
export function ratioFor(slug: string, fallback = '5 / 4'): string {
  const g = grounds[slug];
  return g ? `${g.w} / ${g.h}` : fallback;
}
"""

body = HEADER
for r in rows:
    body += (
        f"  '{r['slug']}': {{ w: {r['w']}, h: {r['h']}, "
        f"top: '{r['top']}', bottom: '{r['bottom']}' }},\n"
    )
body += FOOTER

io.open(OUT, 'w', encoding='utf-8', newline='\n').write(body)
print(f'wrote {os.path.relpath(OUT, ROOT)} — {len(rows)} images')
